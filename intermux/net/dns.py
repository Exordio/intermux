"""DNS servers for namespaces.

A namespace has its own loopback, so local resolvers such as the 127.0.0.53
stub of systemd-resolved are unreachable from inside it, and it has no IPv6.
Only upstream IPv4 servers are used.
"""

from __future__ import annotations

import ipaddress
import os
import re
from typing import Iterable

from intermux.net.interfaces import Interface
from intermux.system.shell import run, which

FALLBACK = ("1.1.1.1", "8.8.8.8")

PRESETS = {
    "Cloudflare": ("1.1.1.1", "1.0.0.1"),
    "Google": ("8.8.8.8", "8.8.4.4"),
    "Quad9": ("9.9.9.9", "149.112.112.112"),
}


def auto_servers(iface: Interface, all_interfaces: list[Interface]) -> list[str]:
    """DNS servers of the interface itself, otherwise the system ones reachable through it.

    A server inside the local network of another interface (say, the Wi-Fi
    router while the namespace goes through a VPN) cannot be reached from the
    namespace, so such servers are skipped.
    """
    servers = _from_resolvectl(iface.name)
    if not servers:
        foreign = [ipaddress.ip_interface(address).network
                   for other in all_interfaces if other.name != iface.name
                   for address in other.ipv4]
        servers = [server for server in _from_resolvectl() or _from_resolv_conf()
                   if not any(ipaddress.ip_address(server) in network for network in foreign)]
    return servers or list(FALLBACK)


def parse(text: str) -> list[str]:
    """Servers from user input: "1.1.1.1, 9.9.9.9" or a preset label such as "Quad9: 9.9.9.9, ..."."""
    label, separator, rest = text.partition(":")
    if separator and label.strip() in PRESETS:
        text = rest
    servers = list(dict.fromkeys(token for token in re.split(r"[,\s]+", text) if token))
    if not servers:
        raise ValueError("No DNS servers given")
    for server in servers:
        try:
            ipaddress.IPv4Address(server)
        except ValueError:
            raise ValueError(f"Not an IPv4 address: {server}") from None
    return servers


def write_resolv_conf(directory: str, servers: Iterable[str]) -> None:
    """Rewrites the file in place: running apps see it through a bind mount of this very inode."""
    os.makedirs(directory, exist_ok=True)
    with open(os.path.join(directory, "resolv.conf"), "w") as f:
        f.write("# Generated by InterMux\n")
        f.writelines(f"nameserver {server}\n" for server in servers)


def read_resolv_conf(directory: str) -> list[str]:
    return _from_resolv_conf(os.path.join(directory, "resolv.conf"))


def _from_resolvectl(link: str | None = None) -> list[str]:
    if not which("resolvectl"):
        return []
    # Lines look like "Global: 1.1.1.1" or "Link 2 (wlan0): 192.168.1.1".
    output = run("resolvectl", "dns", *([link] if link else []), check=False, timeout=3)
    return _upstream(token for line in output.splitlines() for token in line.partition(":")[2].split())


def _from_resolv_conf(path: str = "/etc/resolv.conf") -> list[str]:
    try:
        with open(path) as f:
            return _upstream(parts[1] for parts in map(str.split, f)
                             if len(parts) > 1 and parts[0] == "nameserver")
    except OSError:
        return []


def _upstream(candidates: Iterable[str]) -> list[str]:
    result: list[str] = []
    for candidate in candidates:
        try:
            address = ipaddress.IPv4Address(candidate)
        except ValueError:
            continue
        if not address.is_loopback and not address.is_link_local and candidate not in result:
            result.append(candidate)
    return result
